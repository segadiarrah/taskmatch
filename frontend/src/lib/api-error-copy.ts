/** The original server body stays on ApiError for diagnostics; visible prose is localized. */
export function localizeApiError(message: string, locale: Locale): string {
  if (locale === "en") return message;
  const c = copy[locale];
  const code = messageCodes[message.replace(/\.$/, "")];
  if (code) return c[code];
  const minimum = /^String should have at least (\d+) characters?$/.exec(message);
  if (minimum) return c.minimum.replace("{count}", minimum[1]);
  const maximum = /^String should have at most (\d+) characters?$/.exec(message);
  if (maximum) return c.maximum.replace("{count}", maximum[1]);
  if (/^value is not a valid email address/i.test(message)) return c.email;
  const request = /^Request failed: (\d+)$/.exec(message);
  if (request) {
    const status = Number(request[1]);
    return status === 401 ? c.auth : status === 403 ? c.forbidden : status === 404 ? c.missing : status === 409 ? c.conflict : status === 422 ? c.invalid : status >= 500 ? c.unavailable : c.request;
  }
  return c.request;
}

export function networkError(locale: Locale): string { return copy[locale].network; }

/** Customer-facing payment diagnostics use the service role rather than its vendor. */
export function localizePaymentError(message: string, locale: Locale): string {
  return localizeApiError(message.replace(/stripe/gi, "payment service"), locale);
}
