import {expect,test} from '@playwright/test';

const api=process.env.TASKMATCH_E2E_API;
if(api&&(new URL(api).origin!=='http://127.0.0.1:3171'||process.env.PLAYWRIGHT_BASE_URL!=='http://127.0.0.1:3170'))throw new Error('Use only the isolated journey API and frontend');
test.skip(!api,'Isolated real API must be explicitly provided');

test('real executor signup, registration, pause, activation and capability editing',async({page,request})=>{
  test.setTimeout(90_000);
  if(!api||new URL(api).origin!=='http://127.0.0.1:3171')throw new Error('Use only the isolated journey API');
  page.setDefaultTimeout(12_000);
  const suffix=Date.now().toString();
  const email=`ui-executor-${suffix}@example.com`,password='Browser-test-password-2026';
  const errors:string[]=[];
  page.on('pageerror',()=>errors.push('Runtime exception'));
  page.on('console',m=>{if(m.type()==='error'&&/TypeError|hydration|Cannot read/.test(m.text()))errors.push('Console render exception')});
  await page.addInitScript(()=>localStorage.setItem('taskmatch_locale','en'));
  await page.goto('/register?intent=executor');
  await page.locator('#full_name:visible').fill('Isolated executor owner');
  await page.locator('#email:visible').fill(email);
  await page.locator('#password:visible').fill(password);
  await page.getByRole('button',{name:'Create account',exact:true}).click();
  await expect(page).toHaveURL(/\/developer\/agents\/new$/);
  const auth=await request.post(api+'/api/v1/auth/login',{form:{username:email,password}});
  expect(auth.status()).toBe(200);
  const headers={Authorization:'Bearer '+(await auth.json()).access_token};
  const me=await request.get(api+'/api/v1/auth/me',{headers});expect((await me.json()).role).toBe('agent_developer');
  await page.locator('#name').fill('UI executor '+suffix);
  await page.locator('#description').fill('Real local API registration test');
  await page.locator('#endpoint').fill('https://example.test/journey-executor');
  await page.locator('#task_types').fill('writing,research');
  await page.getByRole('button',{name:'Register Agent',exact:true}).click();
  await expect(page).toHaveURL(/\/developer\/agents\/[0-9a-f-]+$/);
  const id=new URL(page.url()).pathname.split('/').pop();
  await expect(page.locator('main h1')).toHaveText('UI executor '+suffix);
  const getAgent=async()=>{const r=await request.get(api+'/api/v1/agents/'+id,{headers});expect(r.status()).toBe(200);return r.json()};
  expect((await getAgent()).supported_task_types).toEqual(['writing','research']);
  await page.getByRole('button',{name:'Pause Agent',exact:true}).click();
  await expect.poll(async()=>(await getAgent()).status).toBe('paused');
  await page.getByRole('button',{name:'Activate Agent',exact:true}).click();
  await expect.poll(async()=>(await getAgent()).status).toBe('active');
  await page.getByRole('button',{name:'Add',exact:true}).click();
  await page.getByPlaceholder('e.g., python',{exact:true}).fill('journey_research');
  await page.getByPlaceholder('e.g., 3.11',{exact:true}).fill('2.0');
  await page.getByRole('button',{name:'Add',exact:true}).last().click();
  await expect(page.getByRole('button',{name:'Remove journey_research',exact:true})).toBeVisible();
  await expect.poll(async()=>(await getAgent()).capabilities.map((c:any)=>c.capability_name)).toContain('journey_research');
  await page.getByRole('button',{name:'Remove journey_research',exact:true}).click();
  await expect.poll(async()=>(await getAgent()).capabilities.length).toBe(0);
  expect(errors).toEqual([]);
});
