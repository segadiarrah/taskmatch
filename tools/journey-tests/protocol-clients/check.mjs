/** Independent protocol clients over real HTTP against the disposable paid journey API. */
import assert from "node:assert/strict";
import { randomUUID } from "node:crypto";
import { Client, StreamableHTTPClientTransport } from "@modelcontextprotocol/client";
import { ClientFactory, JsonRpcTransportFactory } from "@a2a-js/sdk/client";

const origin = process.argv[2];
if (process.argv.length !== 3 || origin !== "http://127.0.0.1:3172") {
  throw new Error("Pass the disposable journey API origin http://127.0.0.1:3172 explicitly.");
}

async function json(path, init) {
  const response = await fetch(origin + path, { ...init, redirect: "error" });
  if (!response.ok) throw new Error(`${init?.method ?? "GET"} ${path} returned HTTP ${response.status}`);
  return response.json();
}

async function run() {
  // This control route exists only on the fixture launcher, which itself checks
  // the database name, test billing mode, environment and fixture signing key.
  const fixture = await json("/__journey_fixture/state", { headers: { "X-Journey-Fixture": "local-only" } });
  for (const key of ["sessions", "accounts", "transfers", "unexpected"]) {
    assert.ok(Array.isArray(fixture[key]), "Expected the disposable journey fixture");
  }

  const login = await json("/api/v1/auth/login", {
    method: "POST",
    body: new URLSearchParams({ username: "browser-client@taskmatch.ai", password: "Browser-test-password-2026" }),
  });
  assert.ok(login.access_token, "Missing fixture account access token");
  const headers = { authorization: `Bearer ${login.access_token}`, "content-type": "application/json" };
  const principal = await json("/api/v1/principals", {
    method: "POST", headers, body: JSON.stringify({ kind: "individual", display_name: "Independent client fixture" }),
  });
  const contract = {
    schema_version: "tm.human-task.v1", principal_id: principal.id, requester_type: "HUMAN_REQUESTER",
    title: "Independent client translation review", objective: "Check the translation", instructions: "Read the supplied text.",
    task_category: "translation_review", execution_mode: "remote", required_capabilities: ["translation"], language: "fr",
    deadline: new Date(Date.now() + 48 * 3600_000).toISOString(), expected_duration: 30,
    budget: { amount_minor: 1100, currency: "EUR" },
    evidence_requirements: ["report"], authorizations: ["data_owner_consent"],
  };

  const mcp = new Client({ name: "taskmatch-independent-check", version: "1.0.0" }, { versionNegotiation: { mode: "auto" } });
  try {
    await mcp.connect(new StreamableHTTPClientTransport(new URL("/api/v1/protocols/mcp", origin), {
      requestInit: { headers, redirect: "error" },
    }));
    const listing = await mcp.listTools();
    assert.deepEqual(listing.tools.map(tool => tool.name).sort(), [
      "human_task_create", "human_task_events", "human_task_fund", "human_task_get", "human_task_result",
    ]);
    const created = await mcp.callTool({ name: "human_task_create", arguments: { contract, idempotency_key: randomUUID() } });
    assert.ok(!created.isError && created.structuredContent.task_id, "MCP creation failed");
    const taskId = created.structuredContent.task_id;
    const read = await mcp.callTool({ name: "human_task_get", arguments: { task_id: taskId } });
    assert.equal(read.structuredContent.task_id, taskId);

    const card = await json("/api/v1/protocols/a2a/agent-card.json");
    assert.equal(card.protocolVersion, "0.3.0");
    const a2aPath = "/api/v1/protocols/a2a";
    const fixtureEndpoint = new URL(card.url);
    assert.ok([origin, "https://taskmatch.example.test"].includes(fixtureEndpoint.origin));
    assert.equal(fixtureEndpoint.pathname + fixtureEndpoint.search + fixtureEndpoint.hash, a2aPath);
    const factory = new ClientFactory({ transports: [new JsonRpcTransportFactory({
      // The fixture card uses a reserved DNS name. Keep all actual traffic on
      // the same verified loopback origin, including calls generated by the SDK.
      fetchImpl: (input, init) => {
        assert.equal(new URL(input).href, fixtureEndpoint.href);
        const outboundHeaders = new Headers(init?.headers);
        outboundHeaders.set("authorization", headers.authorization);
        return fetch(origin + a2aPath, { ...init, headers: outboundHeaders, redirect: "error" });
      },
    })] });
    const a2a = await factory.createFromAgentCard(card);
    assert.equal((await a2a.getTask({ id: taskId })).id, taskId);
    const second = await a2a.sendMessage({
      message: { messageId: randomUUID(), kind: "message", role: "user", parts: [{ kind: "data", data: { contract } }] },
    });
    assert.ok(second.kind === "task" && second.id, "A2A creation failed");
    assert.equal((await a2a.getTask({ id: second.id })).id, second.id);
    assert.deepEqual(await json(`/api/v1/principals/${principal.id}/webhooks`, { headers }), []);
    console.log("Passed: MCP discovery and five tools, MCP create/get, A2A cross-protocol get and send/get, owner webhook listing. Zero funding or subscription requests.");
  } finally {
    await mcp.close();
  }
}

await run();
