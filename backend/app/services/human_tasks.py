"""Human contracts adapt to the existing Job/Task/Quote execution lifecycle."""
import json
import uuid
from datetime import datetime, timezone
from decimal import Decimal, ROUND_DOWN
from pathlib import Path

from fastapi import HTTPException
from sqlalchemy import func, select
from sqlalchemy.orm import lazyload

from app.middleware.audit import log_audit
from app.models import Job, Task, Quote, TaskQuote
from app.models.human import HumanTaskRequest
from app.schemas.human import HumanTaskContract
from app.services.human_authorization import bound_delegation, owned_principal, request_hash
from app.services.task_access import lock_job

TAXONOMY = json.loads((Path(__file__).parents[1] / 'contracts/taxonomy.v1.json').read_text())
CATEGORIES = {c['id']: c for c in TAXONOMY['categories']}


def validate_policy(body):
    category = CATEGORIES.get(body.task_category)
    if not category or body.execution_mode != category['execution_mode']:
        raise HTTPException(422, 'Unknown category or incompatible execution mode')
    if not set(category['evidence']).issubset(body.evidence_requirements):
        raise HTTPException(422, 'Category evidence requirements are missing')
    if not set(category['authorizations']).issubset(body.authorizations):
        raise HTTPException(422, 'Category authorizations are missing')
    if body.deadline <= datetime.now(timezone.utc):
        raise HTTPException(422, 'The deadline must be in the future')


async def create_contract(db, body, user, delegation, key):
    if body.task_id is not None:
        raise HTTPException(422, 'task_id is generated by TaskMatch')
    # Principal -> delegation -> job -> task. Every creator serializes on principal,
    # so a concurrent replay cannot reserve twice or create a second Job.
    p = await owned_principal(db, body.principal_id, user, lock=True)
    delegation = await bound_delegation(db, delegation, p, body)
    if body.requester_type == 'ORGANIZATION_REQUESTER' and p.kind != 'organization':
        raise HTTPException(422, 'Organization requester requires an organization principal')
    digest = request_hash(body)
    previous = await db.scalar(select(HumanTaskRequest).where(
        HumanTaskRequest.principal_id == p.id, HumanTaskRequest.idempotency_key == key))
    if previous:
        old = await db.get(Task, previous.task_id, options=[lazyload('*')])
        if (previous.request_hash != digest
                or (delegation and old.human_contract_json.get('delegation_id') != str(delegation.id))):
            raise HTTPException(409, 'Idempotency key already binds a different request')
        return old
    validate_policy(body)
    if delegation:
        if delegation.reserved_amount_minor + body.budget.amount_minor > delegation.max_amount_minor:
            raise HTTPException(409, 'Delegation spending limit exceeded')
        delegation.reserved_amount_minor += body.budget.amount_minor
    if body.parent_job_id:
        job = await lock_job(db, body.parent_job_id)
        if job.client_user_id != user.id:
            raise HTTPException(403, 'Parent job belongs to another requester')
        tasks = list((await db.scalars(select(Task).options(lazyload('*')).where(Task.job_id == job.id))).all())
        if (job.status != 'draft' or job.billing_mode != 'stripe' or job.currency != 'EUR' or (delegation and any(not t.human_contract_json for t in tasks))
                or await db.scalar(select(Quote.id).where(Quote.job_id == job.id).limit(1))):
            raise HTTPException(409, 'Adding work requires an unquoted Human Tasks draft job; funded changes require an amendment')
        if any(t.human_contract_json and t.human_contract_json['principal_id'] != str(p.id) for t in tasks):
            raise HTTPException(403, 'Parent job has a different principal')
    else:
        if body.parent_task_id:
            raise HTTPException(422, 'A parent task requires its parent_job_id')
        job = Job(id=uuid.uuid4(), client_user_id=user.id, title=body.title,
                  raw_description=body.objective, budget_min=0,
                  budget_max=Decimal(body.budget.amount_minor)/100, currency='EUR',
                  billing_mode='stripe', status='draft', auto_select_enabled=False)
        db.add(job)
        await db.flush()
    if body.parent_task_id:
        parent = await db.get(Task, body.parent_task_id, options=[lazyload('*')])
        if not parent or parent.job_id != job.id:
            raise HTTPException(422, 'Parent task must belong to the same job')
    task_id = uuid.uuid4()
    canonical = body.model_copy(update={'task_id': task_id, 'parent_job_id': job.id}).model_dump(mode='json')
    task = Task(id=task_id, job_id=job.id, parent_task_id=body.parent_task_id,
                title=body.title, description=body.objective, task_type=body.task_category,
                budget=worker_amount(body.budget.amount_minor), status='pending',
                human_contract_json=canonical, human_policy_status='pending',
                input_spec_json={'requires_human': True},
                output_spec_json={'required_fields': body.evidence_requirements})
    db.add(task)
    await db.flush()
    db.add(HumanTaskRequest(principal_id=p.id, idempotency_key=key,
                           request_hash=digest, task_id=task.id))
    await log_audit(db, actor_type='user', actor_id=str(user.id), action='human_task.created',
                    entity_type='task', entity_id=str(task.id),
                    payload={'principal_id': str(p.id), 'delegation_id': str(delegation.id) if delegation else None,
                             'reserved_minor': body.budget.amount_minor})
    return task


def worker_amount(total_minor):
    # Total includes the existing 10% platform fee. Rounding down cannot exceed mandate.
    return (Decimal(total_minor) / Decimal('110')).quantize(Decimal('.01'), rounding=ROUND_DOWN)


async def require_approved_job(db, job):
    tasks = list((await db.scalars(select(Task).options(lazyload('*')).where(Task.job_id == job.id))).all())
    if any(t.human_contract_json and t.human_policy_status != 'approved' for t in tasks):
        raise HTTPException(409, 'Independent policy review is required before funding or execution')


async def create_human_quote(db, job):
    from app.services.quote_service import ensure_delivery_plan
    tasks = list((await db.scalars(select(Task).options(lazyload('*')).where(Task.job_id == job.id))).all())
    from app.services.billing_service import assert_quote_editable
    await assert_quote_editable(db,job)
    if not tasks:
        raise HTTPException(409,'At least one step is required')
    if any(not t.human_contract_json for t in tasks):
        from app.services.quote_service import create_quote_for_job
        return await create_quote_for_job(db,job.id)
    await require_approved_job(db, job)
    from app.services.billing_service import assert_quote_editable
    await assert_quote_editable(db, job)
    for q in (await db.scalars(select(Quote).where(Quote.job_id == job.id,
                Quote.status.in_(['draft', 'pending_client'])))).all():
        q.status = 'superseded'
    subtotal = sum((worker_amount(t.human_contract_json['budget']['amount_minor']) for t in tasks), Decimal(0))
    fee = (subtotal * Decimal('.10')).quantize(Decimal('.01'))
    total = subtotal + fee
    ceiling = sum(t.human_contract_json['budget']['amount_minor'] for t in tasks)
    if int(total*100) > ceiling:
        raise HTTPException(409, 'Quote exceeds the authorized spending limit')
    # Use serialized creation time, not the possibly older transaction start.
    q = Quote(id=uuid.uuid4(), created_at=func.clock_timestamp(), job_id=job.id, currency='EUR', subtotal=subtotal,
              platform_fee=fee, total=total, pricing_version='tm.human-task.v1',
              status='pending_client', valid_until=min(datetime.fromisoformat(t.human_contract_json['deadline']) for t in tasks),
              breakdown_json={'contract_version': 'tm.human-task.v1', 'authorized_total_minor': ceiling})
    db.add(q)
    await db.flush()
    for t in tasks:
        amount = worker_amount(t.human_contract_json['budget']['amount_minor'])
        t.budget = amount
        db.add(TaskQuote(quote_id=q.id, created_at=func.clock_timestamp(), task_id=t.id, route='human', complexity='S',
                        task_type=t.task_type, price=amount, human_price_low=amount,
                        human_price_high=amount, human_hours=t.human_contract_json['expected_duration']/60,
                        breakdown_json={'contract_version':'tm.human-task.v1'}))
    await ensure_delivery_plan(db, job, {})
    job.budget_max = total
    job.status = 'quoted'
    return q


async def publish(db, task_id, user, review):
    job_id = await db.scalar(select(Task.job_id).where(Task.id == task_id))
    if not job_id:
        raise HTTPException(404, 'Task not found')
    job = await lock_job(db, job_id)
    task = await db.get(Task, task_id, options=[lazyload('*')])
    if not task.human_contract_json:
        raise HTTPException(404, 'Human Task not found')
    if job.client_user_id == user.id:
        raise HTTPException(403, 'Independent publication review is required')
    if job.status not in ('draft', 'quoted'):
        raise HTTPException(409, 'The job is no longer awaiting publication')
    validate_policy(HumanTaskContract.model_validate(task.human_contract_json))
    task.human_policy_status = 'approved'
    await log_audit(db, actor_type='user', actor_id=str(user.id), action='human_task.policy_approved',
                    entity_type='task', entity_id=str(task.id), payload=review.model_dump())
    await db.flush()
    pending = await db.scalar(select(Task.id).where(Task.job_id == job.id,
                                Task.human_policy_status != 'approved').limit(1))
    if pending is None:
        await create_human_quote(db, job)
    return task
